const scratchBytes = 16 << 10
const maxHeaderBytes = 64 << 10
const maxBodyBytes = 64 << 20

type requestHead struct {
	method, target string
	fields         map[string]string
	length         int64
}

type observation struct {
	Mode                   string `json:"mode"`
	TLS                    bool   `json:"tls"`
	ALPN                   string `json:"alpn"`
	Requests               int    `json:"requests"`
	WireBodyBytes          int64  `json:"wire_body_bytes"`
	DecodedBodyBytes       int64  `json:"decoded_body_bytes"`
	BodySHA256             string `json:"body_sha256"`
	UploadBytes            int64  `json:"upload_bytes"`
	UploadSHA256           string `json:"upload_sha256"`
	UploadComplete         bool   `json:"upload_complete"`
	AcceptEncoding         string `json:"accept_encoding"`
	FirstChunkBarrier      bool   `json:"first_chunk_barrier"`
	EarlyFinal             bool   `json:"early_final"`
	AuthorizationGone      bool   `json:"authorization_gone"`
	IntermediateSent       bool   `json:"intermediate_sent"`
	CheapBeforeRelease     bool   `json:"cheap_before_release"`
	DeadlineHandshakeAbort bool   `json:"deadline_handshake_abort"`
}

type fixture struct {
	mode       string
	directory  string
	size       int64
	encrypted  bool
	barrier    bool
	listener   net.Listener
	tlsConfig  *tls.Config
	encoded    []byte
	patternSHA string
	result     observation
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

func require(ok bool, message string) {
	if !ok {
		panic(message)
	}
}

// Pattern has no payload-size allocation and is independently regenerated by
// the native host. A constant-fill gzip case separately exercises amplification.
func pattern(dst []byte, offset int64) {
	for i := range dst {
		at := offset + int64(i)
		dst[i] = byte((at*31 + at/251 + 17) % 256)
	}
}

func digestPattern(size int64) string {
	h := sha256.New()
	var block [scratchBytes]byte
	for at := int64(0); at < size; {
		n := min(int64(len(block)), size-at)
		pattern(block[:n], at)
		_, err := h.Write(block[:n])
		must(err)
		at += n
	}
	return hex.EncodeToString(h.Sum(nil))
}

func writeAll(w io.Writer, payload []byte) error {
	for len(payload) != 0 {
		n, err := w.Write(payload)
		if err != nil {
			return err
		}
		if n < 1 {
			return io.ErrNoProgress
		}
		payload = payload[n:]
	}
	return nil
}

func readHead(reader *bufio.Reader) requestHead {
	var storage []byte
	for len(storage) <= maxHeaderBytes {
		line, err := reader.ReadSlice('\n')
		storage = append(storage, line...)
		require(len(storage) <= maxHeaderBytes, "request header bound")
		if err == bufio.ErrBufferFull {
			continue
		}
		must(err)
		if bytes.HasSuffix(storage, []byte("\r\n\r\n")) {
			break
		}
	}
	lines := strings.Split(string(storage), "\r\n")
	words := strings.Split(lines[0], " ")
	require(len(words) == 3 && words[2] == "HTTP/1.1", "request line")
	h := requestHead{method: words[0], target: words[1], fields: make(map[string]string)}
	for _, line := range lines[1:] {
		if line == "" {
			continue
		}
		name, value, ok := strings.Cut(line, ":")
		require(ok, "request field")
		name = strings.ToLower(name)
		_, duplicate := h.fields[name]
		require(!duplicate, "duplicate request field")
		h.fields[name] = strings.TrimSpace(value)
	}
	require(h.fields["host"] != "", "Host absent")
	if value, ok := h.fields["content-length"]; ok {
		length, err := strconv.ParseInt(value, 10, 64)
		must(err)
		require(length >= 0 && length <= maxBodyBytes, "request body bound")
		h.length = length
	}
	require(h.fields["transfer-encoding"] == "", "unexpected upload coding")
	return h
}

func (f *fixture) marker(name string) {
	must(os.WriteFile(filepath.Join(f.directory, name), []byte(name), 0600))
}

func (f *fixture) wait(name string) {
	cutoff := time.Now().Add(12 * time.Second)
	for time.Now().Before(cutoff) {
		if _, err := os.Stat(filepath.Join(f.directory, name)); err == nil {
			return
		}
		time.Sleep(time.Millisecond)
	}
	panic("coordination timeout: " + name)
}

func (f *fixture) accept(listener net.Listener, encrypted bool) net.Conn {
	conn, err := listener.Accept()
	must(err)
	must(conn.SetDeadline(time.Now().Add(15 * time.Second)))
	if tcp, ok := conn.(*net.TCPConn); ok {
		if strings.HasPrefix(f.mode, "early-final") || f.mode == "upload-stall" || f.mode == "upload-source-error-blocked" {
			must(tcp.SetReadBuffer(4096))
		}
		if f.mode == "credit" || f.mode == "cancel" || f.mode == "timeout" || f.mode == "fairness" {
			must(tcp.SetWriteBuffer(4096))
		}
	}
	if !encrypted {
		return conn
	}
	secure := tls.Server(conn, f.tlsConfig)
	must(secure.Handshake())
	state := secure.ConnectionState()
	require(state.Version == tls.VersionTLS13, "actual TLS version")
	require(state.NegotiatedProtocol == "http/1.1", "actual ALPN")
	f.result.ALPN = state.NegotiatedProtocol
	return secure
}

func (f *fixture) request(conn net.Conn) (*bufio.Reader, requestHead) {
	reader := bufio.NewReaderSize(conn, scratchBytes)
	head := readHead(reader)
	f.result.Requests++
	f.result.AcceptEncoding = head.fields["accept-encoding"]
	return reader, head
}

func (f *fixture) head(conn net.Conn, status int, length int64, fields string) {
	lengthField := ""
	if length >= 0 {
		lengthField = fmt.Sprintf("Content-Length: %d\r\n", length)
	}
	must(writeAll(conn, []byte(fmt.Sprintf("HTTP/1.1 %d Fixture\r\n%s%s\r\n", status, lengthField, fields))))
}

func (f *fixture) streamPattern(conn net.Conn, size int64, chunked, fragmented bool) error {
	var block [scratchBytes]byte
	first := true
	for at := int64(0); at < size; {
		n := min(int64(len(block)), size-at)
		if first && f.barrier {
			n = min(n, 1024)
		}
		pattern(block[:n], at)
		if chunked {
			if err := writeAll(conn, []byte(fmt.Sprintf("%x\r\n", n))); err != nil {
				return err
			}
		}
		if fragmented {
			for _, value := range block[:n] {
				if err := writeAll(conn, []byte{value}); err != nil {
					return err
				}
			}
		} else if err := writeAll(conn, block[:n]); err != nil {
			return err
		}
		if chunked {
			if err := writeAll(conn, []byte("\r\n")); err != nil {
				return err
			}
		}
		at += n
		f.result.WireBodyBytes += n
		if first && f.barrier {
			f.marker("first-written")
			f.wait("first-taken")
			f.result.FirstChunkBarrier = true
		}
		first = false
	}
	if chunked {
		return writeAll(conn, []byte("0\r\nX-Complete: yes\r\n\r\n"))
	}
	return nil
}

func gzipPayload(size int64, repeated bool, metadata bool) []byte {
	var target bytes.Buffer
	writer := gzip.NewWriter(&target)
	if metadata {
		writer.Name = "fixture.bin"
		writer.Comment = "owned independent metadata"
		writer.Extra = bytes.Repeat([]byte{0x19}, 37)
	}
	var block [scratchBytes]byte
	for at := int64(0); at < size; {
		n := min(int64(len(block)), size-at)
		if repeated {
			for i := range block[:n] {
				block[i] = 'A'
			}
		} else {
			pattern(block[:n], at)
		}
		_, err := writer.Write(block[:n])
		must(err)
		at += n
	}
	must(writer.Close())
	require(target.Len() <= maxBodyBytes, "compressed fixture bound")
	return target.Bytes()
}

func withHeaderCRC(payload []byte) []byte {
	require(len(payload) >= 18 && payload[3] == 0, "plain gzip header required")
	header := append([]byte(nil), payload[:10]...)
	header[3] = 2
	var checksum [2]byte
	binary.LittleEndian.PutUint16(checksum[:], uint16(crc32.ChecksumIEEE(header)))
	result := append(header, checksum[:]...)
	return append(result, payload[10:]...)
}

func (f *fixture) prepareCompressed() {
	repeated := f.mode == "gzip-amplification"
	payload := gzipPayload(f.size, repeated, f.mode == "gzip-metadata")
	f.result.DecodedBodyBytes = f.size
	if repeated {
		h := sha256.New()
		var block [scratchBytes]byte
		for i := range block {
			block[i] = 'A'
		}
		for at := int64(0); at < f.size; {
			n := min(int64(len(block)), f.size-at)
			_, err := h.Write(block[:n])
			must(err)
			at += n
		}
		f.result.BodySHA256 = hex.EncodeToString(h.Sum(nil))
	} else {
		f.result.BodySHA256 = digestPattern(f.size)
	}
	switch f.mode {
	case "gzip-crc", "gzip-crc-held":
		payload[len(payload)-8] ^= 1
	case "gzip-size":
		payload[len(payload)-4] ^= 1
	case "gzip-truncated":
		payload = payload[:len(payload)-1]
	case "gzip-trailing":
		payload = append(payload, 'x')
	case "gzip-members":
		payload = append(payload, gzipPayload(31, false, false)...)
	case "gzip-fhcrc", "gzip-fhcrc-invalid":
		payload = withHeaderCRC(payload)
		if f.mode == "gzip-fhcrc-invalid" {
			payload[10] ^= 1
		}
	}
	f.encoded = payload
	f.result.WireBodyBytes = int64(len(payload))
	if f.mode == "buffered-gzip" {
		digest := sha256.Sum256(payload)
		f.result.BodySHA256 = hex.EncodeToString(digest[:])
	}
	must(os.WriteFile(filepath.Join(f.directory, "encoded-length"), []byte(strconv.Itoa(len(payload))), 0600))
}

func (f *fixture) compressed(conn net.Conn) {
	payload := f.encoded
	require(payload != nil, "prepared gzip vector")
	fields := "Content-Encoding: gzip\r\nConnection: close\r\n"
	chunked := f.mode == "gzip-chunked"
	eof := f.mode == "gzip-eof"
	if chunked {
		fields += "Transfer-Encoding: chunked\r\n"
	}
	length := int64(len(payload))
	if chunked || eof {
		length = -1
	}
	f.head(conn, 200, length, fields)
	if chunked {
		for at := 0; at < len(payload); {
			n := min(137, len(payload)-at)
			must(writeAll(conn, []byte(fmt.Sprintf("%x\r\n", n))))
			must(writeAll(conn, payload[at:at+n]))
			must(writeAll(conn, []byte("\r\n")))
			at += n
		}
		must(writeAll(conn, []byte("0\r\n\r\n")))
	} else if f.mode == "gzip-fragmented" {
		for _, value := range payload {
			must(writeAll(conn, []byte{value}))
		}
	} else {
		// A consumer can intentionally terminate on encoded/decoded admission.
		_ = writeAll(conn, payload)
	}
}

func (f *fixture) upload(conn net.Conn, reader *bufio.Reader, head requestHead) {
	require(head.method == "POST", "upload method")
	h := sha256.New()
	if f.mode == "upload-source-error-blocked" {
		f.marker("head-received")
		f.wait("upload-blocked")
		// Do not drain pending body bytes until the native request has already
		// completed. A pending write cannot manufacture progress for this test.
		f.wait("native-failed")
		n, err := io.CopyN(h, reader, head.length)
		f.result.UploadBytes = n
		f.result.UploadSHA256 = hex.EncodeToString(h.Sum(nil))
		require(err != nil && n < head.length, "source-error request transmitted full upload")
		return
	}
	if strings.HasPrefix(f.mode, "early-final") {
		if f.mode == "early-final-blocked" {
			f.marker("head-received")
			f.wait("upload-blocked")
		}
		if f.mode != "early-final" {
			n, err := io.CopyN(h, reader, min(head.length, 64<<10))
			must(err)
			f.result.UploadBytes = n
		}
		f.result.EarlyFinal = true
		f.head(conn, 413, 3, "Connection: close\r\n")
		must(writeAll(conn, []byte("no!")))
		f.marker("final-written")
		// Closing with unread upload bytes can issue TCP RST and erase the valid
		// response before the client reads it. Keep this owned peer alive while
		// boundedly discarding in-flight bytes until the client retires itself.
		remaining := head.length - f.result.UploadBytes
		cap := min(remaining, 4<<20)
		if cap > 0 {
			n, err := io.CopyN(io.Discard, reader, cap)
			f.result.UploadBytes += n
			require(err != nil, "upload continued through drain cap after early final")
		}
		return
	}
	if f.mode == "upload-stall" {
		f.marker("head-received")
		f.wait("release-peer")
		return
	}
	n, err := io.CopyN(h, reader, head.length)
	f.result.UploadBytes = n
	f.result.UploadSHA256 = hex.EncodeToString(h.Sum(nil))
	f.result.UploadComplete = err == nil && n == head.length
	if f.mode == "upload-short" || f.mode == "upload-cancel" || f.mode == "upload-source-error" {
		require(err != nil, "abandoned upload completed")
		return
	}
	must(err)
	require(f.result.UploadSHA256 == digestPattern(head.length), "upload byte identity")
	f.head(conn, 200, 2, "Connection: close\r\n")
	must(writeAll(conn, []byte("ok")))
}

func (f *fixture) response(conn net.Conn) {
	if strings.HasPrefix(f.mode, "gzip") || f.mode == "buffered-gzip" {
		f.compressed(conn)
		return
	}
	f.result.DecodedBodyBytes = f.size
	require(f.patternSHA != "", "expected response digest prepared before readiness")
	f.result.BodySHA256 = f.patternSHA
	switch f.mode {
	case "head-gzip", "no-content-gzip", "not-modified-gzip":
		status := 200
		if f.mode == "no-content-gzip" {
			status = 204
		}
		if f.mode == "not-modified-gzip" {
			status = 304
		}
		f.head(conn, status, f.size, "Content-Encoding: gzip\r\nConnection: close\r\n")
		f.result.DecodedBodyBytes, f.result.WireBodyBytes = 0, 0
		digest := sha256.Sum256(nil)
		f.result.BodySHA256 = hex.EncodeToString(digest[:])
	case "coding-unsupported", "coding-chain", "coding-repeated":
		fields := "Content-Encoding: br\r\n"
		if f.mode == "coding-chain" {
			fields = "Content-Encoding: gzip, gzip\r\n"
		}
		if f.mode == "coding-repeated" {
			fields = "Content-Encoding: gzip\r\nContent-Encoding: gzip\r\n"
		}
		f.head(conn, 200, 3, fields+"Connection: close\r\n")
		_ = writeAll(conn, []byte("bad"))
	case "chunk-invalid-size":
		f.head(conn, 200, -1, "Transfer-Encoding: chunked\r\nConnection: close\r\n")
		must(writeAll(conn, []byte("z\r\n")))
	case "chunk-invalid-crlf":
		f.head(conn, 200, -1, "Transfer-Encoding: chunked\r\nConnection: close\r\n")
		must(writeAll(conn, []byte("3\r\nabcXX0\r\n\r\n")))
	case "chunk-truncated":
		f.head(conn, 200, -1, "Transfer-Encoding: chunked\r\nConnection: close\r\n")
		must(writeAll(conn, []byte("800\r\npartial")))
	case "chunk-missing-terminal":
		f.head(conn, 200, -1, "Transfer-Encoding: chunked\r\nConnection: close\r\n")
		must(writeAll(conn, []byte("3\r\nabc\r\n")))
	case "chunk-trailer-invalid":
		f.head(conn, 200, -1, "Transfer-Encoding: chunked\r\nConnection: close\r\n")
		must(writeAll(conn, []byte("0\r\nnot-a-field\r\n\r\n")))
	case "conflicting-framing":
		f.head(conn, 200, 3, "Transfer-Encoding: chunked\r\nConnection: close\r\n")
		must(writeAll(conn, []byte("0\r\n\r\n")))
	default:
		chunked := f.mode == "chunked"
		eof := f.mode == "eof"
		fields := "Connection: close\r\n"
		length := f.size
		if chunked {
			fields += "Transfer-Encoding: chunked\r\n"
			length = -1
		} else if eof {
			length = -1
		}
		f.head(conn, 200, length, fields)
		size := f.size
		if f.mode == "short-length" || f.mode == "buffered-short" {
			size /= 2
		}
		err := f.streamPattern(conn, size, chunked, f.mode == "fragmented")
		if f.mode == "timeout" || f.mode == "cancel" {
			require(err != nil, "held output peer unexpectedly completed entire response")
			f.marker("transport-retired")
		}
		if f.mode != "credit" && f.mode != "cancel" && f.mode != "timeout" &&
			f.mode != "encoded-limit" && f.mode != "decoded-limit" {
			must(err)
		}
	}
}

func (f *fixture) redirects() {
	finalListener := f.listener
	finalEncrypted := f.encrypted
	if strings.HasPrefix(f.mode, "redirect-cross") || f.mode == "redirect-downgrade" {
		other, err := net.Listen("tcp4", "127.0.0.1:0")
		must(err)
		defer other.Close()
		finalListener = other
		if f.mode == "redirect-downgrade" {
			finalEncrypted = false
		}
	}
	scheme := "http"
	if finalEncrypted {
		scheme = "https"
	}
	location := fmt.Sprintf("%s://%s/final", scheme, finalListener.Addr())
	first := f.accept(f.listener, f.encrypted)
	reader, head := f.request(first)
	_ = reader
	require(head.length == 0 && head.target == "/start", "initial redirect request")
	if f.mode == "redirect-cross-auth" {
		require(head.fields["authorization"] == "Bearer owned-fixture", "initial authorization")
	}
	if f.mode == "redirect-deadline" {
		time.Sleep(150 * time.Millisecond)
	}
	fields := "Location: " + location + "\r\nX-Intermediate: hidden\r\nConnection: close\r\n"
	if f.mode == "redirect-malformed" {
		f.head(first, 302, 16, fields)
		must(writeAll(first, []byte("bad")))
		must(first.Close())
		f.result.IntermediateSent = true
		return
	}
	if f.mode == "redirect-gzip-invalid" {
		payload := gzipPayload(31, false, false)
		payload[len(payload)-8] ^= 1
		f.head(first, 302, int64(len(payload)), fields+"Content-Encoding: gzip\r\n")
		must(writeAll(first, payload))
		must(first.Close())
		f.result.IntermediateSent = true
		return
	}
	f.head(first, 302, 4, fields)
	must(writeAll(first, []byte("skip")))
	must(first.Close())
	f.result.IntermediateSent = true
	f.marker("intermediate-written")
	if f.mode == "redirect" || f.mode == "redirect-cross" {
		f.wait("intermediate-hidden")
	}
	if f.mode == "redirect-cross-auth" {
		tcp := finalListener.(*net.TCPListener)
		must(tcp.SetDeadline(time.Now().Add(300 * time.Millisecond)))
		unexpected, err := tcp.Accept()
		if err == nil {
			unexpected.Close()
			panic("unsafe credentials contacted second origin")
		}
		network, ok := err.(net.Error)
		require(ok && network.Timeout(), "cross-origin rejection observation")
		f.result.AuthorizationGone = true
		return
	}
	if f.mode == "redirect-downgrade" {
		tcp := finalListener.(*net.TCPListener)
		must(tcp.SetDeadline(time.Now().Add(300 * time.Millisecond)))
		unexpected, err := tcp.Accept()
		if err == nil {
			unexpected.Close()
			panic("HTTPS downgrade contacted HTTP peer")
		}
		network, ok := err.(net.Error)
		require(ok && network.Timeout(), "downgrade observation")
		return
	}
	if f.mode == "redirect-loop" {
		for i := 0; i < 2; i++ {
			conn := f.accept(f.listener, f.encrypted)
			_, next := f.request(conn)
			require(next.length == 0, "loop redirect body")
			f.head(conn, 302, 0, fields)
			must(conn.Close())
		}
		return
	}
	var last net.Conn
	if f.mode == "redirect-deadline" && finalEncrypted {
		raw, err := finalListener.Accept()
		must(err)
		must(raw.SetDeadline(time.Now().Add(5 * time.Second)))
		secure := tls.Server(raw, f.tlsConfig)
		if err := secure.Handshake(); err != nil {
			// The immutable total cutoff can expire during a new hop's TLS,
			// before its request head. Native evidence must still prove Deadline
			// at the original cutoff and retain the first validated302 status.
			f.result.DeadlineHandshakeAbort = true
			raw.Close()
			return
		}
		require(secure.ConnectionState().NegotiatedProtocol == "http/1.1", "deadline hop ALPN")
		last = secure
	} else {
		last = f.accept(finalListener, finalEncrypted)
	}
	defer last.Close()
	_, next := f.request(last)
	require(next.target == "/final" && next.length == 0, "followed request")
	if f.mode == "redirect-cross" {
		require(next.fields["authorization"] == "", "cross-origin credentials leaked")
		f.result.AuthorizationGone = true
	}
	if f.mode == "redirect-deadline" {
		time.Sleep(150 * time.Millisecond)
	}
	if f.mode == "redirect-deadline" {
		_ = writeAll(last, []byte("HTTP/1.1 200 Fixture\r\nContent-Length: 2\r\nConnection: close\r\n\r\n"))
	} else {
		f.head(last, 200, 2, "X-Final: yes\r\nConnection: close\r\n")
	}
	_ = writeAll(last, []byte("ok"))
	f.result.DecodedBodyBytes, f.result.WireBodyBytes = 2, 2
	digest := sha256.Sum256([]byte("ok"))
	f.result.BodySHA256 = hex.EncodeToString(digest[:])
}

func makeTLS(directory string) *tls.Config {
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	must(err)
	template := &x509.Certificate{
		SerialNumber: big.NewInt(104), Subject: pkix.Name{CommonName: "localhost"},
		DNSNames: []string{"localhost"}, IPAddresses: []net.IP{net.ParseIP("127.0.0.1")},
		NotBefore: time.Now().Add(-time.Hour), NotAfter: time.Now().Add(time.Hour),
		KeyUsage:              x509.KeyUsageDigitalSignature | x509.KeyUsageCertSign,
		BasicConstraintsValid: true, IsCA: true,
		ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	der, err := x509.CreateCertificate(rand.Reader, template, template, &key.PublicKey, key)
	must(err)
	must(os.WriteFile(filepath.Join(directory, "root.pem"), pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0600))
	return &tls.Config{
		Certificates: []tls.Certificate{{Certificate: [][]byte{der}, PrivateKey: key}},
		MinVersion:   tls.VersionTLS13, MaxVersion: tls.VersionTLS13,
		SessionTicketsDisabled: true, NextProtos: []string{"http/1.1"},
	}
}

func (f *fixture) fairness() {
	cheap, err := net.Listen("tcp4", "127.0.0.1:0")
	must(err)
	defer cheap.Close()
	must(os.WriteFile(filepath.Join(f.directory, "cheap-endpoint"), []byte(cheap.Addr().String()), 0600))
	finished := make(chan bool, 1)
	go func() {
		conn, err := cheap.Accept()
		must(err)
		defer conn.Close()
		must(conn.SetDeadline(time.Now().Add(5 * time.Second)))
		head := readHead(bufio.NewReader(conn))
		require(head.target == "/cheap" && head.length == 0, "cheap request")
		_, err = os.Stat(filepath.Join(f.directory, "transport-retired"))
		require(os.IsNotExist(err), "cheap request waited for held transport retirement")
		must(writeAll(conn, []byte("HTTP/1.1 200 Fixture\r\nContent-Length: 2\r\nConnection: close\r\n\r\nok")))
		finished <- true
	}()
	fmt.Println(f.listener.Addr().String())
	conn := f.accept(f.listener, f.encrypted)
	defer conn.Close()
	_, head := f.request(conn)
	require(head.length == 0, "held response request")
	f.head(conn, 200, f.size, "Connection: close\r\n")
	err = f.streamPattern(conn, f.size, false, false)
	require(err != nil, "held stream unexpectedly completed entire body")
	f.marker("transport-retired")
	f.result.CheapBeforeRelease = <-finished
	f.result.Requests++
}

func main() {
	mode := flag.String("mode", "known", "owned response/upload schedule")
	directory := flag.String("dir", "", "owned finite coordination directory")
	size := flag.Int64("bytes", 32<<20, "decoded entity bytes, at most64MiB")
	encrypted := flag.Bool("tls", false, "TLS1.3 with verified loopback certificate")
	barrier := flag.Bool("first-chunk-barrier", false, "require first chunk before remaining body")
	flag.Parse()
	require(*directory != "" && *size >= 0 && *size <= maxBodyBytes, "fixture options")
	must(os.MkdirAll(*directory, 0700))
	listener, err := net.Listen("tcp4", "127.0.0.1:0")
	must(err)
	defer listener.Close()
	f := fixture{mode: *mode, directory: *directory, size: *size, encrypted: *encrypted, barrier: *barrier, listener: listener}
	f.result.Mode, f.result.TLS = f.mode, f.encrypted
	if f.encrypted {
		f.tlsConfig = makeTLS(f.directory)
	}
	if strings.HasPrefix(f.mode, "gzip") || f.mode == "buffered-gzip" {
		f.prepareCompressed()
	} else if !strings.HasPrefix(f.mode, "upload") && !strings.HasPrefix(f.mode, "early-final") &&
		!strings.HasPrefix(f.mode, "redirect") && f.mode != "fairness" && !strings.HasPrefix(f.mode, "allocation-") {
		// Hash preparation belongs before the endpoint is published: otherwise
		// a 32MiB oracle calculation can consume a short request's entire budget
		// before a single response header or held output chunk exists.
		f.patternSHA = digestPattern(f.size)
	}
	if f.mode == "fairness" {
		f.fairness()
		encoded, err := json.Marshal(f.result)
		must(err)
		fmt.Println(string(encoded))
		return
	}
	fmt.Println(listener.Addr().String())
	if strings.HasPrefix(f.mode, "redirect") {
		f.redirects()
		encoded, err := json.Marshal(f.result)
		must(err)
		fmt.Println(string(encoded))
		return
	}
	conn := f.accept(listener, f.encrypted)
	defer conn.Close()
	if f.mode == "allocation-engine" {
		var one [1]byte
		n, err := conn.Read(one[:])
		require(n == 0 && err != nil, "failed engine emitted HTTP bytes")
		encoded, err := json.Marshal(f.result)
		must(err)
		fmt.Println(string(encoded))
		return
	}
	reader, head := f.request(conn)
	if f.mode == "allocation-head-fields" {
		f.marker("allocation-ready")
		f.wait("allocation-release")
		f.head(conn, 200, 2, "X-Fault-Point: descriptors\r\nConnection: close\r\n")
		_ = writeAll(conn, []byte("ok"))
		encoded, err := json.Marshal(f.result)
		must(err)
		fmt.Println(string(encoded))
		return
	}
	if strings.HasPrefix(f.mode, "upload") || strings.HasPrefix(f.mode, "early-final") {
		f.upload(conn, reader, head)
	} else {
		require(head.length == 0, "response-only request body")
		f.response(conn)
	}
	encoded, err := json.Marshal(f.result)
	must(err)
	fmt.Println(string(encoded))
}
